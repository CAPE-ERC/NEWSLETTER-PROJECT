"""Independent reproducibility and arithmetic checks."""
import csv,json,hashlib,math,sys,zipfile
from pathlib import Path
ROOT=Path(__file__).resolve().parent;D=ROOT/'Results'
def get(n):
 with open(D/n,encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
J=json.loads((D/'forecast.json').read_text());P=get('model_forecasts.csv');C=get('ols_coefficients.csv');V=get('used_predictors.csv');E=get('historical_forecasts.csv');S=get('backtest_scores.csv')
assert len(P)==8 and J['models_eligible']==8
assert J['gdp_release_assumption_days']==60
assert J['gdp_release_calendar_policy']=='assumed_60_calendar_days_all_quarters_no_overrides'
assert len(J['ensemble_weights'])==8
assert all(x>0 for x in J['ensemble_weights'].values())
assert abs(sum(J['ensemble_weights'].values())-1)<1e-10
assert abs(sum(J['ensemble_weights'][n]*J['model_predictions_pct'][n] for n in J['ensemble_weights'])-J['statistical_ensemble_pct'])<1e-10
assert abs(J['statistical_ensemble_pct']+J['expert_adjustment_pp']-J['published_candidate_forecast_pct'])<1e-10
assert abs(J['pi50_lower_pct']+J['pi50_upper_pct']-2*J['published_candidate_forecast_pct'])<1e-10
from decimal import Decimal,ROUND_HALF_UP
def dec2(x):return Decimal(str(x)).quantize(Decimal('0.01'),rounding=ROUND_HALF_UP)
expected_low=(dec2(J['pi50_lower_pct'])*Decimal('1.10')).quantize(Decimal('0.01'),rounding=ROUND_HALF_UP)
expected_up=(dec2(J['pi50_upper_pct'])*Decimal('0.90')).quantize(Decimal('0.01'),rounding=ROUND_HALF_UP)
assert J['reporting_range_lower_pct']==float(expected_low)
assert J['reporting_range_upper_pct']==float(expected_up)
assert J['reporting_range_lower_pct']<=J['published_candidate_forecast_pct']<=J['reporting_range_upper_pct']
assert J['reporting_bound_adjustment_fraction']==0.10
coefs={x['term']:float(x['coefficient']) for x in C};variables={x['variable']:float(x['value']) for x in V}
assert len(variables)==4 and len(coefs)==5
ols=coefs['Intercept']+sum(coefs[k]*v for k,v in variables.items())
assert abs(ols-J['model_predictions_pct']['OLS with intercept'])<1e-8
assert J['ensemble_weights']['OLS with intercept']>0
assert J['best_single_model_last8'] in J['ensemble_weights']
assert all(x not in J['ensemble_weights'] for x in ('Random Forest','Histogram Boosting'))
assert all(r['model'] not in ('Random Forest','Histogram Boosting') for r in P)
assert all(r['model'] not in ('Random Forest','Histogram Boosting') for r in E)
assert all(r['model'] not in ('Random Forest','Histogram Boosting') for r in S)
assert len(E)>300 and len(S)>40
# Match last 8-24 RMSE and MAE using saved origin-level records.
for s in S:
 rr=sorted((r for r in E if r['vintage']==s['vintage'] and r['model']==s['model']),key=lambda r:r['as_of_date'])[-int(s['window_quarters']):]
 if not rr:raise AssertionError(s)
 errors=[float(x['error_pp']) for x in rr]
 assert len(errors)==int(s['n'])
 assert abs(math.sqrt(sum(e**2 for e in errors)/len(errors))-float(s['rmse_pp']))<1e-9
 assert abs(sum(abs(e) for e in errors)/len(errors)-float(s['mae_pp']))<1e-9
 assert all(r['as_of_date']<r['gdp_release_date'] for r in rr)
# Excel generated by the standard openpyxl reporting script.
# --skip-excel is still permitted, but --require-excel enforces dashboard delivery.
excel = D/'Nigeria_GDP_8_Model_Results.xlsx'
if excel.exists():
 with zipfile.ZipFile(excel) as zipped:
  assert zipped.testzip() is None, 'Excel workbook is corrupted'
  assert 'xl/workbook.xml' in zipped.namelist(), 'Excel workbook structure is incomplete'
  xml=zipped.read('xl/workbook.xml').decode('utf-8')
  for sheet_name in ('Executive Summary','Best Models','All Model Forecasts',
                     'Backtest Scores','OLS Coefficients','Model Inputs',
                     'Historical Errors','Methodology and Caveats','PI50 Audit'):
   assert 'name="'+sheet_name+'"' in xml, f'Missing Excel sheet: {sheet_name}'
 # Validate dashboard values against the independently validated JSON output.
 from openpyxl import load_workbook
 wb=load_workbook(excel,read_only=True,data_only=False)
 report=wb['Executive Summary']
 assert abs(report['B5'].value-J['statistical_ensemble_pct'])<1e-10
 assert abs(report['B8'].value-J['pi50_lower_pct'])<1e-10
 assert abs(report['B9'].value-J['pi50_upper_pct'])<1e-10
 assert report['B7'].value=='=B5+B6'
 assert report['B10'].value=='=ROUND(ROUND(B8,2)*1.10,2)'
 assert report['B11'].value=='=ROUND(ROUND(B9,2)*0.90,2)'
 wb.close()
 print('Excel workbook: PRESENT, 9 sheets; contents and interval formulas validated')
elif '--require-excel' in sys.argv:
 raise SystemExit('Excel workbook not found. Run python run_nigeria_nowcast.py without --skip-excel; openpyxl is installed via requirements_model.txt.')
else:
 print('Excel workbook: SKIPPED by --skip-excel or not generated; CSV/JSON checks passed.')
master=ROOT.parent.parent/'Main Data'/'MultipleFrequencyModelData.xlsx'
assert master.is_file(), f'Shared master workbook not found: {master}'
from openpyxl import load_workbook
master_wb=load_workbook(master,read_only=True,data_only=True)
assert {'monthly data','Quarterly Data'}.issubset(master_wb.sheetnames)
monthly_headers=[str(cell.value).strip() if cell.value is not None else '' for cell in master_wb['monthly data'][2]]
for required in ('Date','HCPI','MPR','M2','CPS','PMI','Inflation_Risk_Index'):
 assert required in monthly_headers, f'Missing shared-master field: {required}'
master_wb.close()
print('PASS: core 8-model forecasts, OLS weighting, PI50, 10%-adjusted range, historical errors, data integrity')
